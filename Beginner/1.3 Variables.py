principal_amount = 100
rate_of_interest = 8.2
time_period = 3
simple_interest = (principal_amount * rate_of_interest * time_period) / 100
print(f"Principal Amount (P) : {principal_amount}")
print(f"Rate of Interest (R) : {rate_of_interest}%")
print(f"Time Period (T)      : {time_period} years")
print(f"Calculated Simple Interest = {simple_interest}")